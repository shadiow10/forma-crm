const COPY: Record<Lang, Copy> = { fr, en, ar };
// Short label for the switch itself, full name for screen readers.
export const LANGS: { id: Lang; short: string; name: string }[] = [
  { id: "fr", short: "FR", name: "Français" },
  { id: "en", short: "EN", name: "English" },
  { id: "ar", short: "عربي", name: "العربية" },
];

export const useT = () => COPY[useLang()];

// Spread on the root element of each public page. Deliberately not on <html>: the signed-in
// app is French and is not laid out for right-to-left, so it must not inherit either one.
export function usePage() {
  const lang = useLang();
  return { lang, dir: lang === "ar" ? "rtl" as const : "ltr" as const };
}

// Grouped like 7 900 — with a plain space, since the narrow one Intl uses is missing from our
// display font. Only the currency word changes language.
export const money = (value: number, copy: Copy) =>
  `⁦${new Intl.NumberFormat("fr-FR").format(value).replace(/[\u202f\u00a0]/g, " ")} ${copy.currency}⁩`;

// Three buttons rather than a <select>: the dropdown a select opens is drawn by the operating
// system, which ignores the page theme, and all three languages fit in the same width anyway.
export function LangPicker({ label }: { label: string }) {
  const lang = useLang();
  return <span className="lang-picker" role="group" aria-label={label}>
    <Icon name="globe" size={15} />
    {LANGS.map((item) => (
      <button key={item.id} type="button" lang={item.id} aria-label={item.name} aria-pressed={lang === item.id}
        className={lang === item.id ? "on" : ""} onClick={() => setLang(item.id)}>{item.short}</button>
    ))}
  </span>;
}
