-- Rooms: the school's rooms, which groups use them, and which are free.
--
-- Until now a group's room was free text ("Salle 1", "salle 1 ", "S1"…), so nothing could tell
-- which rooms exist or which are taken. A school now lists its rooms here; the group form offers
-- only the rooms free on the chosen days and hours, and the rooms page shows who studies where.
--
-- groups.room stays a text column holding the room's name. Linking by id would have meant
-- rewriting every existing group and every screen that prints a room; matching by name keeps the
-- groups that already say "Salle 1" attached to the new room "Salle 1". A rename follows through to
-- the groups (trigger below), so the two never drift apart.

create table rooms (
  id bigint generated by default as identity primary key,
  school_id bigint not null references schools(id) on delete cascade,
  name text not null check (length(trim(name)) between 1 and 60),
  capacity integer check (capacity > 0),          -- seats; empty = not given
  created_at timestamptz not null default now(),
  unique (school_id, name)
);
create index on rooms (school_id);

alter table rooms enable row level security;
-- The director manages the rooms; the office and teachers read them (the timetable shows them).
create policy "director manages rooms" on rooms for all to authenticated
  using (private.has_role(school_id, '{director}')) with check (private.has_role(school_id, '{director}'));
create policy "members read rooms" on rooms for select to authenticated
  using (private.has_role(school_id, '{secretaire,teacher}'));
-- Same frozen-school rule as every other table (0016).
create policy "frozen read-only insert" on rooms as restrictive for insert to authenticated with check (not private.is_frozen(school_id));
create policy "frozen read-only update" on rooms as restrictive for update to authenticated using (not private.is_frozen(school_id));
create policy "frozen read-only delete" on rooms as restrictive for delete to authenticated using (not private.is_frozen(school_id));

-- 0005's rule: the id and creation time never change from the app.
revoke update on rooms from anon, authenticated;
grant update (name, capacity) on rooms to authenticated;

-- A renamed room keeps its groups; a deleted room leaves them "room to be set".
create function private.follow_room_name()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'UPDATE' then
    update public.groups set room = new.name where school_id = new.school_id and room = old.name;
    return new;
  end if;
  update public.groups set room = null where school_id = old.school_id and room = old.name;
  return old;
end $$;
create trigger follow_room_name after update of name or delete on rooms
  for each row execute function private.follow_room_name();

-- Schools that already typed room names get those rooms listed, so the page is not empty on day one.
-- Stray spaces first, so "Salle 1 " and "Salle 1" become one room.
update groups set room = nullif(trim(room), '') where room is distinct from nullif(trim(room), '');
insert into rooms (school_id, name)
select distinct school_id, trim(room) from groups where room is not null and trim(room) <> ''
on conflict (school_id, name) do nothing;
